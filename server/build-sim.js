// Bundles the game's simulation scripts (the same files the browser loads) into one ES module for the Worker.
// Each room calls createSim() and gets its own private R namespace, because several rooms (Durable Objects)
// can share one isolate and the browser scripts keep their state on window.R.
// Run: node build-sim.js   (npm run dev / deploy do this first)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = ['flags', 'core', 'body', 'props', 'maps', 'echo', 'weapons', 'bots', 'game'];

let out = '// GENERATED by build-sim.js from the game scripts. Do not edit.\n';
out += 'export function createSim() {\n';
out += '  const window = { location: { search: "" }, localStorage: null, REVERB_HEADLESS: true };\n';
out += '  const document = undefined, requestAnimationFrame = undefined, localStorage = undefined;\n';
for (const f of FILES) {
  out += `  // ---- ${f}.js ----\n` + fs.readFileSync(path.join(ROOT, f + '.js'), 'utf8') + '\n';
}
out += '  return window.R;\n}\n';
fs.writeFileSync(path.join(__dirname, 'src', 'sim.gen.js'), out);
console.log('wrote src/sim.gen.js from', FILES.length, 'game scripts');
